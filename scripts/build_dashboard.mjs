// Build the dashboard's data files from the raw scans.
//   xhs_authors.json  → dashboard/data.js   (creators to follow, with avatars)
//   me.json           → dashboard/me.js     (your notes, categorized + analyzed)
//
// Both outputs load via <script>, so the dashboard works opened straight from
// disk (file:// blocks fetch). Both are gitignored — tooling is public, your
// data is local.
//
// Categorization + analysis live HERE, not in the puller: pure transform, safe
// to re-run and tweak without spending API calls.
//
// Usage: node scripts/build_dashboard.mjs [--lang en|zh]
//   --lang sets the dashboard's default UI language (the UI also has a live toggle).
//   Category LABELS are bilingual; category KEYWORDS stay Chinese (they match Chinese posts).

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const langArg = (process.argv.find(a => a.startsWith('--lang')) || '').split('=')[1]
  || (process.argv[process.argv.indexOf('--lang') + 1] === 'en' ? 'en' : null);
const LANG = langArg === 'en' ? 'en' : 'zh';
const read = f => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));
const write = (f, obj) => {
  fs.mkdirSync(path.join(root, 'dashboard'), { recursive: true });
  fs.writeFileSync(path.join(root, 'dashboard', f),
    `// Generated by scripts/build_dashboard.mjs — do not edit, gitignored.\nwindow.CM_LANG = ${JSON.stringify(LANG)};\nwindow.${f === 'me.js' ? 'ME' : 'SCAN'} = ${JSON.stringify(obj)};\n`);
};

// ── categories ──────────────────────────────────────────────────────────
// Keyword rules over title+desc. First rule with the most hits wins; ties go
